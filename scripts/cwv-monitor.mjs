// Core Web Vitals trend for the top pages: Lighthouse (pinned via npx, no repo
// dependency) on Playwright's Chromium, mobile, both the simulated model (what
// PageSpeed Insights reports) and applied 4G throttling (closer to real users).
// Appends one JSON line per page to cwv/trend.jsonl and rewrites cwv/latest.md.
// INP is a field metric: lab runs record TBT as its proxy; field INP needs CrUX
// with an API key (APPROVALS W20). Run: node scripts/cwv-monitor.mjs [--only <n>]
import { execFileSync } from 'node:child_process';
import { appendFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

export const PAGES = [
  '/', '/events', '/venues', '/artists', '/download', '/link', '/about', '/guides',
  '/city?city=Denver', '/city?city=Las%20Vegas', '/city?city=San%20Francisco', '/city?city=Los%20Angeles',
  '/genre?genre=House', '/events?when=weekend&city=Denver', '/events?festival=1', '/search?q=red%20rocks',
  '/guides/red-rocks-edm-guide', '/guides/first-rave-guide', '/privacy', 'https://app.trydropapp.com/',
];
const MODES = { simulated: [], applied: ['--throttling-method=devtools'] };

export function summarize(report) {
  const a = report.audits;
  const num = (id) => (a[id] && typeof a[id].numericValue === 'number' ? Math.round(a[id].numericValue * (id === 'cumulative-layout-shift' ? 1000 : 1)) / (id === 'cumulative-layout-shift' ? 1000 : 1) : null);
  return {
    perf: report.categories?.performance?.score == null ? null : Math.round(report.categories.performance.score * 100),
    lcp_ms: num('largest-contentful-paint'), cls: num('cumulative-layout-shift'), fcp_ms: num('first-contentful-paint'),
    tbt_ms: num('total-blocking-time'), inp_ms: null,
  };
}

// Google's thresholds: LCP ≤2.5 s good / ≤4 s needs improvement; CLS ≤0.1 / ≤0.25.
export function rating(row) {
  const lcp = row.lcp_ms == null ? '?' : row.lcp_ms <= 2500 ? 'good' : row.lcp_ms <= 4000 ? 'needs-improvement' : 'poor';
  const cls = row.cls == null ? '?' : row.cls <= 0.1 ? 'good' : row.cls <= 0.25 ? 'needs-improvement' : 'poor';
  return { lcp, cls };
}

export function latestMarkdown(rows, when) {
  const head = '| Page | Mode | Perf | LCP | CLS | TBT (INP proxy) |\n|---|---|---|---|---|---|\n';
  return '# CWV latest (' + when + ')\n\nMobile Lighthouse 13.5.0. Generated by `scripts/cwv-monitor.mjs`; history in `trend.jsonl`.\n\n' + head +
    rows.map((r) => `| ${r.url} | ${r.mode} | ${r.perf ?? '–'} | ${r.lcp_ms == null ? '–' : (r.lcp_ms / 1000).toFixed(2) + ' s'} (${rating(r).lcp}) | ${r.cls ?? '–'} (${rating(r).cls}) | ${r.tbt_ms ?? '–'} ms |`).join('\n') + '\n';
}

async function chromePath() {
  const { chromium } = await import('@playwright/test');
  return chromium.executablePath();
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const only = process.argv.includes('--only') ? Number(process.argv[process.argv.indexOf('--only') + 1]) : PAGES.length;
  const env = { ...process.env, CHROME_PATH: await chromePath() };
  const when = new Date().toISOString();
  const rows = [];
  for (const page of PAGES.slice(0, only)) {
    const url = page.startsWith('http') ? page : 'https://trydropapp.com' + page;
    for (const [mode, flags] of Object.entries(MODES)) {
      let row;
      try {
        const out = execFileSync('npx', ['--yes', 'lighthouse@13.5.0', url, '--only-categories=performance', '--form-factor=mobile',
          '--chrome-flags=--headless=new', '--output=json', '--output-path=stdout', '--quiet', ...flags], { env, maxBuffer: 64 << 20, timeout: 180000 });
        row = { when, url: page, mode, ...summarize(JSON.parse(out)) };
      } catch (error) {
        row = { when, url: page, mode, error: String(error.message || error).slice(0, 160) };
      }
      rows.push(row);
      appendFileSync(new URL('../cwv/trend.jsonl', import.meta.url), JSON.stringify(row) + '\n');
      console.log(mode.padEnd(9), page, row.error ? 'ERROR ' + row.error : `LCP ${row.lcp_ms} ms CLS ${row.cls}`);
    }
  }
  writeFileSync(new URL('../cwv/latest.md', import.meta.url), latestMarkdown(rows, when));
}
